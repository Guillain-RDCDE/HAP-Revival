#!/usr/bin/env python3
"""
HAP-Revival web UI — a minimal HTML5 control surface for the Sony HAP-Z1ES /
HAP-S1, served by Python's stdlib http.server.

This is the first working third-party HAP control web app. Open it in any
modern browser; it displays now-playing and lets you pause/resume/seek.

Updates arrive by push: the server subscribes to the player's UDP notification
stream (see hap_notify.py) and the browser long-polls /api/events, so a track
change shows up the moment it happens rather than on the next poll. A timer
still runs underneath — it moves the progress bar and it takes over entirely
when push isn't available (player asleep, mock device, or --no-push). It ticks
at 3 s without push and 10 s with it.

It is also an installable **PWA**: on iPhone/iPad, Safari → Share → "Add to
Home Screen" gives a standalone full-screen remote with its own icon (no App
Store needed). See docs/13-control-app.md.

The page itself lives next to this file, in `tools/web/`: `index.html` (the
whole UI — markup, CSS and script), `manifest.webmanifest` and `sw.js` (the
service worker). The icon set is `tools/pwa/*.png`, generated by
make_pwa_icons.py. Every asset is re-read from disk on each request, so the
template can be edited without restarting the server.

Stdlib-only. Run with:

    python tools/webui.py <hap-ip>
    python tools/webui.py --port 8080 192.168.1.28

Then open http://localhost:8080 in your browser.

Features:
    - Now-playing: title, artist, album, cover art, elapsed/total time, audio
      quality info, with the page's ambient colour taken from the cover.
    - Live progress bar, advanced locally once a second between refreshes.
    - Pause / Resume / Next / Previous buttons; seek by clicking the bar.
    - Sound settings (DSEE, DSD remastering, gapless, oversampling), sleep
      timer, favourites, volume where the player has one.
    - The front panel mirrored, with its keys.
    - Library browse and search over the REST catalogue; the "to fix" list.
    - Power button (wake/standby). Identity info: model, firmware.

Not here:
    - Playlist management.
    - WebSocket (the HAP has none — its push mechanism is UDP, and it is used).
    - Multi-device fleet view.
"""

